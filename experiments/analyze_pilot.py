"""R6: audit the committed 24-trial schedule against controller exports.

This is an *offline data-integrity and descriptive analysis tool*, not a study
of intelligence and not verification of conductor-side receipt time.

No synthetic observations are generated by this production script. All test
fixtures in tests/test_pilot_analysis.py are clearly labelled synthetic.
"""
from __future__ import annotations

import argparse
from collections import Counter, defaultdict
import hashlib
import json
import math
import os
from pathlib import Path

from .pilot_schedule import PROTOCOL, commitment, generate, public_commitment


class EvidenceError(ValueError):
    pass


HYPOTHESES = ("no_human", "human_A", "human_B")
PHASE_MARKER = "The fixed baseline is complete. Continue interrogation."


def check_private_schedule(plan: dict, published: dict | None = None) -> None:
    if not isinstance(plan, dict):
        raise EvidenceError("Private schedule must be a JSON object")
    seed = plan.get("seed")
    try:
        expected = generate(seed)
    except (ValueError, TypeError) as error:
        raise EvidenceError("Invalid private schedule seed") from error
    if plan != expected:
        raise EvidenceError("Private schedule differs from deterministic seeded assignment")
    if published is not None:
        if published != public_commitment(plan):
            raise EvidenceError("Published commitment does not match sealed plan")
    if plan.get("protocol") != PROTOCOL or plan["commitment"] != commitment(seed):
        raise EvidenceError("Pilot schedule protocol/commitment mismatch")


def _proper_probabilities(verdict) -> bool:
    if not isinstance(verdict, dict):
        return False
    p = verdict.get("p")
    if not isinstance(p, dict) or set(p) != set(HYPOTHESES):
        return False
    if any(type(value) not in (int, float) or not math.isfinite(value)
           or not 0 <= value <= 1 for value in p.values()):
        return False
    return abs(sum(p.values()) - 1) <= 1e-6


def _truth(condition: str) -> str:
    return {"humanA": "human_A", "humanB": "human_B",
            "machineA": "no_human", "machineB": "no_human",
            "unchanged": "no_human"}[condition]


def _first(events: list[dict], kind: str):
    return next((event for event in events if event.get("kind") == kind), None)


def audit_trial(assignment: dict, record: dict | None, witness: list[dict] | None = None):
    """Compare source export to the *assigned* intervention, not to its claim alone.

    Returns all observed problems; no selection or repairing of invalid runs.
    Only controller exports after reveal may count as fully completed.
    """
    errors = []
    trial_id = assignment["trial_id"]
    origin, link = assignment["origin"], assignment["link_after"]
    result = {
        "trial_id": trial_id, "origin": origin, "link_after": link,
        "assigned_condition": assignment["condition"], "valid": False,
        "brier": None, "p_human": None, "witness_coverage": False,
        "errors": errors,
    }
    if record is None:
        errors.append("missing_controller_export")
        return result
    if not isinstance(record, dict):
        errors.append("malformed_controller_export")
        return result

    def require(ok, label):
        if not ok:
            errors.append(label)

    require(record.get("schema") == "reverse-turing-trial/v1", "wrong_export_schema")
    require(record.get("pilot_enabled") is True, "pilot_not_enabled")
    require(record.get("pilot_aborted") is False, "pilot_aborted")
    require(record.get("pilot_valid_for_primary") is True, "engine_pilot_invalid")
    require(record.get("revealed") is True, "trial_not_revealed")
    require(record.get("pilot_resumed") is True, "phase_not_resumed")
    require(record.get("pacing_seconds") == 45.0, "wrong_gate")
    require(record.get("condition") == assignment["condition"], "assignment_mismatch")
    expected_links = {"A_to_B": link == "on", "B_to_A": link == "on"}
    require(record.get("links") == expected_links, "link_factor_mismatch")
    require(record.get("human_gateway") is assignment["human_gateway"],
            "human_gateway_mismatch")
    require(record.get("timing_violations") == [], "internal_timing_violation")
    require(record.get("pilot_question_count") == 8, "question_count_mismatch")

    events = record.get("public")
    audit = record.get("audit")
    if not isinstance(events, list) or not isinstance(audit, list):
        errors.append("missing_event_or_audit_lists")
        return result
    try:
        if not all(type(x.get("sequence")) is int for x in events + audit):
            raise ValueError("sequence")
        public = sorted(events, key=lambda e: e["sequence"])
        actions = sorted(audit, key=lambda e: e["sequence"])
    except (TypeError, KeyError, ValueError):
        errors.append("event_schema_invalid")
        return result

    question = [e for e in public if e.get("kind") == "question"]
    answer = [e for e in public if e.get("kind") == "answer"]
    timeout = [e for e in public if e.get("kind") == "timeout"]
    markers = [e for e in public if e.get("kind") == "phase"]
    require(len(question) == 8, "eight_questions_required")
    require(len(answer) == 8, "eight_answers_required")
    require(not timeout, "explicit_timeout")
    require(len(markers) == 1, "exactly_one_public_marker")
    if len(question) == 8:
        require([e.get("channel") for e in question[:2]] == ["A", "B"],
                "baseline_order_mismatch")
    if len(markers) == 1:
        marker = markers[0]
        require(marker.get("channel") == "C"
                and marker.get("speaker") == "CTRL"
                and marker.get("body") == PHASE_MARKER,
                "public_marker_content_mismatch")
        if len(question) == 8:
            require(question[1]["sequence"] < marker["sequence"]
                    < question[2]["sequence"], "phase_marker_wrong_position")
        if len(answer) >= 2:
            require(answer[1]["sequence"] < marker["sequence"],
                    "baseline_not_completed_at_marker")
    for q in question:
        after = [e for e in public if e["sequence"] > q["sequence"]
                 and e.get("kind") in ("answer", "timeout", "question")]
        require(bool(after) and after[0].get("kind") == "answer"
                and after[0].get("channel") == q.get("channel"),
                "question_answer_pairing_invalid")
    if len(answer) == 8:
        require([a.get("channel") for a in answer[:2]] == ["A", "B"],
                "baseline_answer_order_mismatch")

    setups = [a for a in actions if a.get("kind") == "configure_pilot"]
    transitions = [a for a in actions if a.get("kind") == "intervene"]
    resumes = [a for a in actions if a.get("kind") == "resume_pilot"]
    verdicts = [a for a in actions if a.get("kind") == "verdict"]
    reveals = [a for a in actions if a.get("kind") == "reveal"]
    require(len(setups) == 1, "missing_or_duplicated_pilot_setup")
    require(len(transitions) == 1, "missing_or_duplicated_intervention")
    require(len(resumes) == 1, "missing_or_duplicated_resume")
    require(len(verdicts) == 1, "missing_or_duplicated_verdict")
    require(len(reveals) == 1, "missing_or_duplicated_reveal")
    if setups:
        require(setups[0].get("protocol") == "RTT-PILOT/1"
                and setups[0].get("gate_seconds") == 45.0,
                "pilot_setup_differs_from_preregistration")
    if transitions:
        trans = transitions[0]
        require(trans.get("condition") == assignment["condition"],
                "intervention_audit_mismatch")
        require(trans.get("links") == expected_links, "intervention_link_audit_mismatch")
        require(trans.get("human_gateway") is assignment["human_gateway"],
                "intervention_gateway_audit_mismatch")
        if len(answer) >= 2:
            require(answer[1]["sequence"] < trans["sequence"],
                    "intervention_precedes_genuine_baseline")
    if len(markers) == 1 and transitions:
        require(transitions[0]["sequence"] < markers[0]["sequence"],
                "intervention_not_before_public_marker")
    if len(markers) == 1 and resumes:
        require(resumes[0]["sequence"] > markers[0]["sequence"],
                "resumption_audit_order_mismatch")
    if verdicts and reveals:
        require(verdicts[0]["sequence"] < reveals[0]["sequence"],
                "premature_reveal")
    if question and verdicts:
        require(question[-1]["sequence"] < verdicts[0]["sequence"],
                "premature_verdict")

    v = record.get("verdict")
    if _proper_probabilities(v):
        p = v["p"]
        result["p_human"] = 1.0 - p["no_human"]
        truth = _truth(assignment["condition"])
        calculated_brier = sum((p[h] - (1 if h == truth else 0)) ** 2
                               for h in HYPOTHESES)
        result["brier"] = calculated_brier
        declared_score = record.get("score")
        require(isinstance(declared_score, dict), "missing_declared_score")
        if isinstance(declared_score, dict):
            require(declared_score.get("true_class") == truth, "incorrect_score_truth")
            require(type(declared_score.get("brier")) in (int, float)
                    and math.isfinite(declared_score["brier"])
                    and abs(declared_score["brier"] - calculated_brier) <= 1e-9,
                    "brier_disagrees_with_raw_verdict")
        if verdicts:
            require(verdicts[0].get("p") == p, "verdict_audit_differs_from_record")
    else:
        errors.append("invalid_probability_vector")

    if witness is not None:
        validate_witness(trial_id, public, witness, errors)
        result["witness_coverage"] = not any(
            err.startswith("witness_") for err in errors
        )
    else:
        # Absence of optional witness is a missing evidence channel, not
        # proof of a valid receipt time or automatic exclusion from the
        # *descriptive* origin/link comparison.
        result["witness_coverage"] = False

    result["valid"] = not errors
    return result


def validate_witness(trial_id, raw_public, lines, errors):
    """Match a separate public-only observer trace to the controller transcript."""
    if not isinstance(lines, list) or not lines:
        errors.append("witness_missing_records")
        return
    head = lines[0]
    if (head.get("type") != "witness_header"
            or head.get("schema") != "reverse-turing-observer/v1"
            or head.get("trial_id") != trial_id):
        errors.append("witness_header_mismatch")
        return
    ends = [l for l in lines if l.get("type") == "witness_end"]
    if len(ends) != 1 or ends[0].get("last_sequence") != len(raw_public):
        errors.append("witness_incomplete")
    records = [l for l in lines if l.get("type") == "public_event_first_seen"]
    if [r.get("sequence") for r in records] != list(range(1, len(raw_public) + 1)):
        errors.append("witness_sequence_mismatch")
        return
    for raw, witness in zip(raw_public, records):
        payload = {
            "kind": raw.get("kind"), "channel": raw.get("channel"),
            "speaker": raw.get("speaker"), "body": raw.get("body"),
        }
        data = json.dumps(payload, ensure_ascii=False, sort_keys=True,
                          separators=(",", ":")).encode("utf-8")
        if hashlib.sha256(data).hexdigest() != witness.get("payload_sha256"):
            errors.append("witness_digest_mismatch")
            break
        if (type(witness.get("response_complete_monotonic_ns")) is not int
                or type(witness.get("request_started_monotonic_ns")) is not int
                or witness["response_complete_monotonic_ns"]
                   < witness["request_started_monotonic_ns"]):
            errors.append("witness_clock_invalid")
            break


def analyze(plan: dict, records: dict[str, dict], *, witnesses=None, published=None):
    check_private_schedule(plan, published)
    expected_ids = {row["trial_id"] for row in plan["trials"]}
    unexpected = sorted(set(records) - expected_ids)
    if unexpected:
        raise EvidenceError("Unexpected trial IDs in record directory: " +
                            ", ".join(unexpected))
    rows = [
        audit_trial(assignment, records.get(assignment["trial_id"]),
                    None if witnesses is None else witnesses.get(assignment["trial_id"]))
        for assignment in plan["trials"]
    ]
    buckets = defaultdict(list)
    for row in rows:
        if row["valid"] and row["p_human"] is not None:
            buckets[(row["origin"], row["link_after"])].append(row["p_human"])
    cells = {}
    for origin in ("human", "machine", "unchanged"):
        for link in ("on", "off"):
            values = buckets[(origin, link)]
            key = origin + "/" + link
            cells[key] = {
                "n_valid": len(values), "raw_p_human": values,
                "mean_p_human": sum(values) / len(values) if values else None,
                "min_p_human": min(values) if values else None,
                "max_p_human": max(values) if values else None,
            }
    off = cells["machine/off"]["mean_p_human"]
    on = cells["machine/on"]["mean_p_human"]
    delta = None if off is None or on is None else off - on
    valid = sum(row["valid"] for row in rows)
    coverage = sum(row["witness_coverage"] for row in rows)
    return {
        "schema": "reverse-turing-pilot-analysis/v1",
        "protocol": PROTOCOL,
        "seed_commitment_verified": True,
        "n_allocated": len(rows), "n_valid": valid,
        "n_invalid_or_missing": len(rows) - valid,
        "n_with_witness_coverage": coverage,
        "all_allocations_valid": valid == len(rows),
        "externally_verified_conductor_receipt": False,
        "confirmatory_ready": False,
        "interpretation": "descriptive_only_unvalidated_conductor_receipt",
        "primary_delta_machine_off_minus_on": delta,
        "primary_formula": "mean(1-P(no_human)|machine/off)-mean(1-P(no_human)|machine/on)",
        "cells": cells, "rows": rows,
    }


def _load_json(path: Path):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, ValueError) as error:
        raise EvidenceError("Cannot read valid JSON from " + path.name) from error


def _load_witness(path: Path):
    try:
        return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines()
                if line.strip()]
    except (OSError, UnicodeError, ValueError) as error:
        raise EvidenceError("Cannot read witness JSONL " + path.name) from error


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Audit genuine controller exports against a sealed pilot schedule"
    )
    parser.add_argument("--private-schedule", required=True)
    parser.add_argument("--public-commitment", required=True)
    parser.add_argument("--records-dir", required=True)
    parser.add_argument("--witness-dir")
    parser.add_argument("--output", required=True)
    args = parser.parse_args(argv)
    try:
        plan = _load_json(Path(args.private_schedule))
        published = _load_json(Path(args.public_commitment))
        directory = Path(args.records_dir)
        records = {p.stem: _load_json(p) for p in directory.glob("RTT-*.json")}
        witnesses = None
        if args.witness_dir:
            witnesses = {
                p.stem: _load_witness(p)
                for p in Path(args.witness_dir).glob("RTT-*.jsonl")
            }
        output = Path(args.output)
        if output.exists():
            raise EvidenceError("Refusing to overwrite an existing analysis output")
        report = analyze(plan, records, witnesses=witnesses, published=published)
        fd = os.open(str(output), os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            json.dump(report, f, indent=2, sort_keys=True)
            f.write("\n")
        print("Assigned:", report["n_allocated"],
              "valid:", report["n_valid"],
              "invalid/missing:", report["n_invalid_or_missing"])
        print("Descriptive off-minus-on machine-control delta:",
              report["primary_delta_machine_off_minus_on"])
        print("Confirmatory status: NOT READY (no verified conductor receipt)")
        return 0
    except (EvidenceError, OSError, ValueError) as error:
        print("Pilot analysis error:", str(error))
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
